#!/usr/bin/env python3
"""Fits the drum classifier of Convert to MIDI (ReBuzz/Core/AudioLibrary/AudioToMidi/DrumModel.cs) and writes its coefficients.

Development data only: the TRAIN and VALIDATION splits of the Groove MIDI Dataset (Magenta, CC BY 4.0), fetched with

    tools/convert/fetch_data.py --gmd DIR --gmd-split train --gmd-all-types --gmd-per-drummer 45
    tools/convert/fetch_data.py --gmd DIR --gmd-split validation --gmd-per-drummer 12

whose features are dumped by the evaluation tool (ConvertEval --gmd DIR --feat-dump FEATDIR). The TEST split is never read here: it is what
ConvertEval scores. The audio is never kept; what is committed is the coefficients (DrumModelData.cs) and nothing else.

    train_drums.py --features FEATDIR [FEATDIR ...] --out ReBuzz/Core/AudioLibrary/AudioToMidi/DrumModelData.cs

Method: a 1-hidden-layer (64 ReLU) multi-label network, the mean of 3 seeds. The per-class thresholds are chosen on out-of-fold predictions of the
whole development set (5 folds by recording, 3 seeds each), maximising each class's F-measure (hits within 50 ms, one to one), so no recording or
drummer decides a threshold alone.
"""
import argparse, glob, json, os
import numpy as np
from sklearn.neural_network import MLPClassifier

C = ["kick", "snare", "closed hat", "open hat", "tom", "cymbal"]
HID, ALPHA, SEEDS, FOLDS = 64, 1e-2, 3, 5


def load(dirs):
    R = []
    for d in dirs:
        for f in sorted(glob.glob(d + "/*.feat.csv")):
            rows = [l.strip().split(",") for l in open(f) if l.strip()]
            if not rows:
                continue
            t = np.array([float(r[0]) for r in rows])
            y = np.array([[int(c) for c in r[1]] for r in rows])
            X = np.array([[float(v) for v in r[2:]] for r in rows], dtype=np.float32)
            truth = json.load(open(f.replace(".feat.csv", ".truth.json")))
            R.append((os.path.basename(f), t, X, y, truth))
    seen, out = set(), []
    for r in R:
        if r[0] not in seen:
            seen.add(r[0]); out.append(r)
    return out


def score(R, P, thr):
    tp = np.zeros(6); fp = np.zeros(6); fn = np.zeros(6)
    for (name, t, X, y, truth), p in zip(R, P):
        for c in range(6):
            det = t[p[:, c] >= thr[c]]
            tt = np.array(sorted(h[0] for h in truth if h[1] == C[c]))
            used = np.zeros(len(tt), bool); ok = 0
            for d in det:
                if len(tt) == 0:
                    break
                dd = np.abs(tt - d); dd[used] = 9
                j = dd.argmin()
                if dd[j] <= 0.05:
                    used[j] = True; ok += 1
            tp[c] += ok; fp[c] += len(det) - ok; fn[c] += len(tt) - ok
    return 2 * tp / np.maximum(1, 2 * tp + fp + fn), tp, fp, fn


def fit(X, Y, mu, sd, seeds):
    return [MLPClassifier((HID,), alpha=ALPHA, max_iter=400, early_stopping=True, random_state=s).fit((X - mu) / sd, Y) for s in seeds]


def proba(ms, X, mu, sd):
    return sum(m.predict_proba((X - mu) / sd) for m in ms) / len(ms)


def export(path, members, mu, sd, thr, note):
    def arr(a):
        return "{ " + ", ".join(("%.5g" % v) + "f" for v in np.asarray(a).ravel()) + " }"
    L = ["#nullable disable", "// Generated by tools/convert/train_drums.py (see DrumModel.cs). " + note,
         "namespace ReBuzz.Core.AudioLibrary.AudioToMidi", "{", "    internal static class DrumModelData", "    {"]
    L.append("        public static readonly float[] Mean = " + arr(mu) + ";")
    L.append("        public static readonly float[] Sd = " + arr(sd) + ";")
    L.append("        public static readonly float[] Threshold = " + arr(thr) + ";")
    L.append("        public static readonly int[] Hidden = { " + ", ".join(str(m.coefs_[0].shape[1]) for m in members) + " };")
    for name, get in (("W1", lambda m: m.coefs_[0].T), ("B1", lambda m: m.intercepts_[0]), ("W2", lambda m: m.coefs_[1].T), ("B2", lambda m: m.intercepts_[1])):
        L.append("        public static readonly float[][] %s = {" % name)
        for m in members:
            L.append("            new float[] " + arr(get(m)) + ",")
        L.append("        };")
    L += ["    }", "}"]
    open(path, "w", newline="\n").write("\n".join(L) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--features", nargs="+", required=True)
    ap.add_argument("--extra-train", nargs="*", default=[], help="feature folders used for fitting only, never for choosing thresholds (the synthetic kit of ConvertEval --synth)")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    dev = load(a.features)
    extra = load(a.extra_train) if a.extra_train else []
    EX = np.vstack([r[2] for r in extra]) if extra else np.zeros((0, 1)); EY = np.vstack([r[3] for r in extra]) if extra else np.zeros((0, 1))
    print(len(dev), "recordings,", sum(len(r[1]) for r in dev), "candidates")
    oof = [None] * len(dev)
    for k in range(FOLDS):
        tr = [i for i in range(len(dev)) if i % FOLDS != k]
        X = np.vstack([dev[i][2] for i in tr] + ([EX] if extra else [])); Y = np.vstack([dev[i][3] for i in tr] + ([EY] if extra else []))
        mu = X.mean(0); sd = X.std(0) + 1e-3
        ms = fit(X, Y, mu, sd, range(100 * k, 100 * k + SEEDS))
        for i in range(len(dev)):
            if i % FOLDS == k:
                oof[i] = proba(ms, dev[i][2], mu, sd)
    thr = np.full(6, 0.5)
    for c in range(6):
        best = (-1, 0.5)
        for th in np.arange(0.05, 0.85, 0.05):
            t2 = thr.copy(); t2[c] = th
            f = score(dev, oof, t2)[0][c]
            if f > best[0]:
                best = (f, th)
        thr[c] = best[1]
    f, tp, fp, fn = score(dev, oof, thr)
    print("out-of-fold thresholds", np.round(thr, 2), "F", np.round(f * 100, 1), "all", round(100 * 2 * tp.sum() / (2 * tp.sum() + fp.sum() + fn.sum()), 1))
    X = np.vstack([r[2] for r in dev] + ([EX] if extra else [])); Y = np.vstack([r[3] for r in dev] + ([EY] if extra else []))
    mu = X.mean(0); sd = X.std(0) + 1e-3
    ms = fit(X, Y, mu, sd, range(SEEDS))
    export(a.out, ms, mu, sd, thr, "Fitted on %d recordings of the Groove MIDI Dataset train and validation splits (CC BY 4.0) and %d synthetic loops." % (len(dev), len(extra)))
    print("wrote", a.out)
