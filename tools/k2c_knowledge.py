#!/usr/bin/env python3
# Fork (docs/specs/agent-knowledge.md, K2 batch c): what an agent is told about the FSM, Oomek, Polac and Joachims machines
# (27 machines), and the curation of the manifests that were profiled drafts or generated from source. The same shape as
# tools/jeskola_knowledge.py (batch b); the data is in tools/k2c_fsm.py, tools/k2c_oomek_joachims.py and tools/k2c_polac.py.
#
#  - EXPLAIN: a How sentence and a Sound sentence for every parameter, global and track, of the 27 machines; they go into the
#    manifest as "how" and "sound".
#  - CURATE: for the machines that were drafts or generated from source: a type, a summary, plain names, roles, quirks and
#    evidence. For the machines that were hand-curated already (FSM Infector, KickXP, PanzerDelay, the three Oomek ones,
#    Joachims Mars filter 2) an entry may carry "add_quirks" and "add_evidence" and per-parameter overrides ("over") only.
#
# A parameter is found by its position in its group ("p3" is the fourth global parameter, "t0" the first track parameter),
# because some of these machines repeat names (Joachims Enceladus Tube EQ's four bands, Jupiter 3's three compressors) and
# the profiled drafts of the Polac and Philthy machines give every track parameter index 0; a name works where it is unique.
#
# These machines are mostly closed-source DLLs; where ExternalMachines/source has the code (the FSM and Oomek ones) the
# mappings and the behaviour were read from it, otherwise from the machine's own parameter descriptions, value texts and the
# profile (tools/machine-profiler.py on windows). Everything is in our own words. What no source or measurement shows is
# said to be unverified in the sentence, the quirks and the page.
#
#   python3 tools/k2c_knowledge.py            check: the manifests carry this curation and Explain text
#   python3 tools/k2c_knowledge.py --write    write it into the ones tools/native_manifests.py doesn't generate

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import k2c_fsm  # noqa: E402
import k2c_oomek_joachims  # noqa: E402
import k2c_polac  # noqa: E402
import k2d_builtin  # noqa: E402  (K2 batch d: ReBuzz's own machines, the Rout 909, the synths and the control and utility machines)
import k2d_control  # noqa: E402
import k2d_synths  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPLAIN = {**k2c_fsm.EXPLAIN, **k2c_oomek_joachims.EXPLAIN, **k2c_polac.EXPLAIN, **k2d_builtin.EXPLAIN, **k2d_control.EXPLAIN, **k2d_synths.EXPLAIN}
CURATE = {**k2c_fsm.CURATE, **k2c_oomek_joachims.CURATE, **k2c_polac.CURATE, **k2d_builtin.CURATE, **k2d_control.CURATE, **k2d_synths.CURATE}
# Generated from source by tools/native_manifests.py (the FSM natives) and tools/source_manifests.py (ReBuzz's own machines): they call curate and explain themselves.
FROM_SOURCE = ["FSM WahMan", "FSM WahManPro", "FSM WahPro2", "FSM Chorus2", "FSM PhatMan", "AudioBlock", "Connection Mixer Console", "EnvelopeBlock", "QuickNote", "ReBuzz Audio In",
               "ReBuzz Audio Out", "ReBuzz Groove", "ReBuzz Midi Output", "Session Clip Player", "ManagedMultiIOEffect"]
GROUPS = (("parameters", "p"), ("track_parameters", "t"))


def find(table, group, pos, name):
    """The table's entry for a parameter: by its position ("p3", "t0"), else by its name."""
    key = f"{group}{pos}"
    if key in table:
        return key
    if name in table:
        return name
    return None


def curate(m):
    """The profiled draft or generated manifest dict made curated (in place): type, summary, quirks, evidence, plain names, roles."""
    c = CURATE.get(m["gear"])
    if c is None:
        return m
    handmade = m["status"] == "curated" and not m.get("source", "").startswith("generated by")
    if handmade and "add_quirks" not in c and "params" not in c and "new_summary" not in c:
        return m
    out = {}
    for k, v in m.items():
        if k == "status" and not handmade:
            v = "curated"
        if k == "source" and not handmade:
            if v.startswith("generated by"):
                v = v.split("; curated by")[0] + "; curated by tools/k2c_knowledge.py"
            else:
                v = ("curated by hand (2026-11-14, agent-knowledge.md K2 batch c or d) with tools/k2c_knowledge.py, from the profile by "
                     "tools/machine-profiler.py on windows, 2026-11-14 and the evidence listed")
        if "type" in c and k == "type" and not handmade:
            v = c["type"]
        if "summary" in c and k == "summary" and not handmade:
            v = c["summary"]
        if "new_summary" in c and k == "summary":
            v = c["new_summary"]
        if k in ("quirks", "evidence") and handmade:
            v = list(v) + [q for q in c.get("add_" + k, []) if q not in v]
        out[k] = v
        if k == "summary" and not handmade:
            out["quirks"] = list(c["quirks"])
            out["evidence"] = list(c["evidence"])
    m.clear()
    m.update(out)
    used = set()
    for group, g in GROUPS:
        for pos, e in enumerate(m.get(group, [])):
            key = find(c.get("params", {}), g, pos, e["name"])
            if key is None:
                if handmade:
                    continue
                raise SystemExit(f"{m['gear']}: no curation for {group[:-1]} {g}{pos} {e['name']!r}")
            used.add(key)
            plain, role, *over = c["params"][key]
            if over:
                for k, v in over[0].items():
                    if k == "drop":
                        for d in v:
                            e.pop(d, None)
                    elif k == "add_points":   # raw values its table lacks (the profiler read its texts at a step, or the text isn't a number)
                        pts = [pt for pt in e["points"] if pt[0] not in {raw for raw, _ in v}] + [list(x) for x in v]
                        e["points"] = sorted(pts, key=lambda pt: pt[0])
                    else:
                        e[k] = v
            if handmade:
                continue
            new = {}
            for k, v in e.items():
                if k in ("confidence", "suggested_role", "role_evidence"):
                    continue
                new[k] = v
                if k == "name":
                    new["plain_name"] = plain
                    if role:
                        new["role"] = role
            e.clear()
            e.update(new)
    extra = set(c.get("params", {})) - used
    if extra:
        raise SystemExit(f"{m['gear']}: curation for parameters it does not have: {sorted(extra)}")
    return m


def explain(m):
    """The manifest dict with how and sound on every parameter (in place)."""
    texts = EXPLAIN.get(m["gear"])
    if texts is None:
        return m
    used = set()
    for group, g in GROUPS:
        for pos, e in enumerate(m.get(group, [])):
            key = find(texts, g, pos, e["name"])
            if key is None:
                raise SystemExit(f"{m['gear']}: no Explain text for {group[:-1]} {g}{pos} {e['name']!r}")
            how, sound = texts[key]
            used.add(key)
            for k in ("how", "sound"):
                e.pop(k, None)
            e["how"], e["sound"] = how, sound
            if not e.get("description"):   # a draft's parameter had none: the How sentence says what it is (K2 batch d)
                e["description"] = how
    extra = set(texts) - used
    if extra:
        raise SystemExit(f"{m['gear']}: Explain text for parameters it does not have: {sorted(extra)}")
    return m


def path_of(gear):
    for sub in ("Effects", "Generators"):
        p = os.path.join(ROOT, "Machines", "Manifests", sub, gear + ".machine.json")
        if os.path.exists(p):
            return p
    raise SystemExit(f"no manifest for {gear}")


def dump(m):
    return json.dumps(m, indent=1, ensure_ascii=False) + "\n"


def run(write):
    problems = []
    for gear in sorted(set(EXPLAIN) | set(CURATE)):
        if gear in FROM_SOURCE:
            continue
        path = path_of(gear)
        with open(path, encoding="utf-8-sig") as f:
            before = f.read()
        text = dump(explain(curate(json.loads(before))))
        if text != before:
            if write:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
            else:
                problems.append(f"{gear}: its curation or Explain text is not what tools/k2c_knowledge.py says (python3 tools/k2c_knowledge.py --write)")
    return problems


if __name__ == "__main__":
    found = run("--write" in sys.argv[1:])
    for p in found:
        print(p)
    print(("wrote" if "--write" in sys.argv[1:] else "checked") + f" {len(set(EXPLAIN) | set(CURATE)) - len(FROM_SOURCE)} manifests, {len(found)} problems")
    sys.exit(1 if found else 0)
