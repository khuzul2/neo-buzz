#!/usr/bin/env python3
"""Writes a trained Net (model.py) as the flat weight file BeatModelNet.Load reads (ReBuzz/Core/Clips/BeatModelNet.cs), and, for AW2b, as the generated C# data
file BeatModelData.cs.  Also writes the parity file of the tests: a tiny random-weight network, a random input and PyTorch's outputs.

    export.py --ckpt best.pt --out model.aw2m [--cs ReBuzz/Core/Clips/BeatModelData.cs]
    export.py --parity ReBuzz.SessionTests/AutoWarp/aw2-parity.bin
"""
import argparse, base64, struct
import numpy as np
import torch
from model import Net, MELS, TEMPO_BINS


def tensors(net):
    sd = net.state_dict()
    t = lambda k: sd[k].detach().cpu().numpy().astype("<f4").ravel()
    out = []
    for i in (1, 2, 3):
        out += [t("conv%d.weight" % i), t("conv%d.bias" % i)]
    out += [t("proj.weight"), t("proj.bias"), t("ln0.ln.weight"), t("ln0.ln.bias")]
    for b in range(len(net.blocks)):
        p = "blocks.%d." % b
        out += [t(p + "dw.weight"), t(p + "dw.bias"), t(p + "ln.ln.weight"), t(p + "ln.ln.bias"),
                t(p + "p1.weight"), t(p + "p1.bias"), t(p + "p2.weight"), t(p + "p2.bias")]
    out += [t("lnf.ln.weight"), t("lnf.ln.bias"), t("head.weight"), t("head.bias"), t("tempo.weight"), t("tempo.bias")]
    return out


def from_bytes(data):
    """The inverse of to_bytes: a Net with the weights of an AW2M file (AW2c continues the training of the shipped model from them)."""
    assert data[:4] == b"AW2M"
    fmt, version, c1, c2, c3, d, k, ratio, blocks, bins = struct.unpack("<10i", data[4:44])[0:10] if False else struct.unpack("<iiiiiiiiii", data[4:44])
    dil = list(struct.unpack("<%di" % blocks, data[44:44 + 4 * blocks]))
    net = Net(c1=c1, c2=c2, c3=c3, d=d, k=k, ratio=ratio, dil=dil)
    off = 44 + 4 * blocks
    names = []
    for i in (1, 2, 3):
        names += ["conv%d.weight" % i, "conv%d.bias" % i]
    names += ["proj.weight", "proj.bias", "ln0.ln.weight", "ln0.ln.bias"]
    for b in range(blocks):
        p = "blocks.%d." % b
        names += [p + n for n in ("dw.weight", "dw.bias", "ln.ln.weight", "ln.ln.bias", "p1.weight", "p1.bias", "p2.weight", "p2.bias")]
    names += ["lnf.ln.weight", "lnf.ln.bias", "head.weight", "head.bias", "tempo.weight", "tempo.bias"]
    sd = net.state_dict()
    for n in names:
        cnt = sd[n].numel()
        sd[n] = torch.from_numpy(np.frombuffer(data, "<f4", cnt, off).copy()).reshape(sd[n].shape)
        off += 4 * cnt
    assert off == len(data), "the file has more numbers than the network"
    net.load_state_dict(sd)
    return net


def to_bytes(net, version):
    c = net.cfg
    head = b"AW2M" + struct.pack("<iiiiiiiiii", 1, version, c["c1"], c["c2"], c["c3"], c["d"], c["k"], c["ratio"], len(c["dil"]), TEMPO_BINS)
    head += struct.pack("<%di" % len(c["dil"]), *c["dil"])
    return head + b"".join(x.tobytes() for x in tensors(net))


def cs_file(data, path, note):
    b64 = base64.b64encode(data).decode()
    parts = [b64[i:i + 4000] for i in range(0, len(b64), 4000)]
    L = ["#nullable disable", "// Generated by tools/aw2/export.py (see BeatModelNet.cs). " + note, "namespace ReBuzz.Core.Clips", "{",
         "    internal static class BeatModelData", "    {", "        public static readonly string[] Parts = {"]
    L += ['            "%s",' % p for p in parts]
    L += ["        };", "        public static byte[] Bytes() => System.Convert.FromBase64String(string.Concat(Parts));", "    }", "}"]
    open(path, "w", newline="\n").write("\n".join(L) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt"); ap.add_argument("--out"); ap.add_argument("--cs"); ap.add_argument("--version", type=int, default=1)
    ap.add_argument("--parity"); ap.add_argument("--note", default="")
    a = ap.parse_args()
    if a.parity:
        torch.manual_seed(7)
        net = Net(c1=4, c2=4, c3=8, d=16, k=5, dil=[1, 2, 5], ratio=2)
        for p in net.parameters():
            torch.nn.init.normal_(p, 0, 0.3)
        net.eval()
        T = 150
        q = np.random.RandomState(3).randint(0, 200, size=(T, MELS)).astype(np.uint8)
        x = torch.from_numpy(q.astype(np.float32) / 36.0)[None]
        with torch.no_grad():
            beat, tempo = net(x)
        data = to_bytes(net, 99)
        with open(a.parity, "wb") as f:
            f.write(struct.pack("<ii", len(data), T)); f.write(data); f.write(q.tobytes())
            f.write(beat[0].numpy().astype("<f4").T.copy().tobytes())      # (T, 2)
            f.write(tempo[0].numpy().astype("<f4").tobytes())               # tempo logits of the whole excerpt
        print("parity file", a.parity)
    else:
        ck = torch.load(a.ckpt, map_location="cpu")
        net = Net(**ck["cfg"]); net.load_state_dict(ck["state"]); net.eval()
        data = to_bytes(net, a.version)
        if a.out: open(a.out, "wb").write(data)
        if a.cs: cs_file(data, a.cs, a.note)
        print("params", sum(p.numel() for p in net.parameters()), "bytes", len(data))
