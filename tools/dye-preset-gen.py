#!/usr/bin/env python3
"""Dye Essence's factory library, the part a script writes (docs/specs/dye-essence.md section 7, P4c).

    python3 tools/dye-preset-gen.py                       writes the generated presets into Machines/DyeEssence/Presets.txt
    python3 tools/dye-preset-gen.py --report              the same, then prints what the library covers
    python3 tools/dye-preset-gen.py --apply-levels FILE   reads the level test's table (name <TAB> loudest-50-ms RMS dB <TAB> peak dB)
                                                          and moves each generated preset's Volume toward -22 dB (tools/dye-levels.json)
    python3 tools/gen-machine-presets.py Machines/DyeEssence    then writes the preset file ReBuzz loads

The library is data (tools/dye_library.py): bases (a sound, with the engine, the filter, the envelopes and a few parameters it
is about), modifiers (tone, time, layer, motion) and effect recipes (the rack's twelve types, in units). This script combines
them with a seeded generator (the seed is in dye_library.SEED; every choice is a function of the seed and the base's key, so a
run gives the same text every time), checks that no two presets are near-duplicates (parameter-space distance, the same
measure the library test uses) and writes "Category — Name" presets with a comment each. Everything it writes sits under a
marker line at the end of Presets.txt; the presets above the marker (the 76 of P0 to P4b2) are never touched.

The result is curated, not trusted: the library test (NeoBuzz.MachineTests/DyePresetLibraryTests.cs) measures every preset
(level -22 +- 1 dB, no clipping, in tune, distinct) and the generator drops what it cannot tell apart.
"""
import importlib.util
import json
import math
import os
import re
import sys
import zlib
import random

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FOLDER = os.path.join(ROOT, 'Machines', 'DyeEssence')
PRESETS = os.path.join(FOLDER, 'Presets.txt')
LEVELS = os.path.join(HERE, 'dye-levels.json')
MARKER = '# ---- Generated by tools/dye-preset-gen.py (seed %d). Do not edit below by hand: change tools/dye_library.py and run the script. ----'
TARGET_DB = -22.0
NAME_MAX = 32
MIN_DISTANCE = 1.1          # parameter-space distance between any two generated presets (the test asks for 1.0 of all)

sys.path.insert(0, HERE)


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, file))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


genparams = load('genparams', 'gen-machine-params.py')
genpresets = load('genpresets', 'gen-machine-presets.py')
import dye_library as L  # noqa: E402

PARAMS = genparams.parse(os.path.join(FOLDER, 'Params.def'))['params']
BY_NAME = {}
for _i, _p in enumerate(PARAMS):
    _p['index'] = _i
    BY_NAME[_p['id'].lower()] = _p
    BY_NAME[_p['name'].lower()] = _p

FX_TYPE_NAMES = ['Off', 'EQ', 'Filter', 'Comp', 'Clipper', 'Delay', 'Verb', 'Dimension', 'Bitcrusher', 'Freq shift', 'Pitch delay',
                 'Convolution', 'Vocoder']
LIMITS = {'F1 cutoff': (20, 20000), 'F2 cutoff': (20, 20000), 'Amp attack': (0.0005, 20), 'Amp decay': (0.0005, 20),
          'Amp release': (0.0005, 20), 'Flt attack': (0.0005, 20), 'Flt decay': (0.0005, 20), 'Flt release': (0.0005, 20),
          'F1 reso': (0, 100), 'Amp sustain': (0, 100), 'Flt sustain': (0, 100)}
OP = re.compile(r'^(.+?)\s*(\*=|\+=|>=|<=|=)\s*(.*)$')


def parse(text):
    """'a = 1; b *= 2' -> [(key, op, value)]"""
    out = []
    for part in re.split(r'[;\n]', text):
        part = part.strip()
        if not part:
            continue
        m = OP.match(part)
        if not m:
            raise SystemExit(f'cannot read "{part}"')
        out.append((m.group(1).strip(), m.group(2), m.group(3).strip()))
    return out


def num(v):
    try:
        return float(v)
    except ValueError:
        return None


def fmt(v):
    if isinstance(v, float):
        if abs(v - round(v)) < 1e-9:
            return str(int(round(v)))
        return ('%.4g' % v)
    return str(v)


def apply(patch, text):
    for key, op, val in parse(text):
        if op == '=':
            patch[key] = val
            continue
        cur = num(patch.get(key, ''))
        x = num(val)
        if cur is None or x is None:
            raise SystemExit(f'"{key} {op} {val}": the patch has no number for {key}')
        if op == '*=':
            cur *= x
        elif op == '+=':
            cur += x
        elif op == '>=':
            cur = max(cur, x)
        elif op == '<=':
            cur = min(cur, x)
        if key in LIMITS:
            cur = min(LIMITS[key][1], max(LIMITS[key][0], cur))
        patch[key] = fmt(cur)


def stable(*parts):
    return zlib.crc32('|'.join(str(p) for p in parts).encode('utf-8'))


def free_index(patch, pattern, count, first=1):
    used = {int(m.group(1)) for k in patch for m in [re.match(pattern, k)] if m}
    return [i for i in range(first, count + 1) if i not in used]


def engines(patch):
    return [patch.get(f'{s} engine', 'Wavetable' if s == 'A' else 'Off') for s in 'ABC']


def used_slots(patch):
    return sum(1 for e in engines(patch) if e != 'Off')


class Variant:
    def __init__(self, base, mods, fxs, duo):
        self.base, self.mods, self.fxs, self.duo = base, mods, fxs, duo


def realise(var, levels):
    """The patch lines (an ordered dict), name and comment of a variant; None when it does not fit."""
    base = var.base
    patch = {}
    apply(patch, L.COMMON)
    apply(patch, base['patch'])
    desc = [base['desc']]
    pre, post = [], []
    for mod in var.mods:
        if mod.get('req') and not mod['req'](patch):
            return None
        text = mod['patch']
        if '{L}' in text or '{R' in text or '{E}' in text:
            lfos = free_index(patch, r'LFO(\d+) shape', 4)
            routes = free_index(patch, r'R(\d+) source', 16)
            envs = free_index(patch, r'Env(\d+) attack', 2)
            need_r = text.count('{R}') + text.count('{R2}')
            if ('{L}' in text and not lfos) or len(routes) < need_r or ('{E}' in text and not envs):
                return None
            text = text.replace('{L}', str(lfos[0]) if lfos else '1').replace('{R}', str(routes[0]) if routes else '1')
            text = text.replace('{R2}', str(routes[1]) if len(routes) > 1 else '2').replace('{E}', str(envs[0]) if envs else '1')
        apply(patch, text)
        if mod.get('pre'):
            pre.append(mod['pre'])
        if mod.get('post'):
            post.append(mod['post'])
        desc.append(mod['desc'])
    if var.duo and used_slots(patch) > 2:
        return None
    state = {}
    if base.get('state'):
        state.update(base['state'])
    for mod in var.mods:
        if mod.get('state'):
            state.update(mod['state'])
    if var.duo:
        patch['FX layout'] = 'Duo'
    taken = set()
    returns = {}
    for fx in var.fxs:
        if fx['role'] == 'serial':
            slots = [8, 9, 10] if not var.duo else [1, 2, 3, 4]
        else:
            if var.duo:
                slots = [8, 9, 10]
            else:
                slots = [5, 6, 7] if fx.get('bus') == 'B' else [1, 2, 3, 4]
        free = [s for s in slots if s not in taken]
        if not free:
            return None
        n = free[0]
        taken.add(n)
        patch[f'FX{n} type'] = fx['type']
        patch[f'FX{n} mix'] = fmt(float(fx['mix']))
        for k, v in sorted(fx['p'].items()):
            patch[f'FX{n} p{k}'] = fmt(float(v))
        if fx['role'] == 'parallel':
            bus = 'A' if (var.duo or fx.get('bus') != 'B') else 'B'
            if bus in returns:
                return None
            returns[bus] = fx['ret']
            patch[f'FX return {bus}'] = fmt(float(fx['ret']))
        desc.append(fx['desc'])
        if fx.get('post'):
            post.append(fx['post'])
    nw = {w.lower() for w in base['noun'].split()}
    pre = [w for w in pre if not ({x.lower() for x in w.split()} & nw)]
    post = [w for w in post if not ({x.lower() for x in w.split()} & nw)]
    words = [' '.join(pre[:1] + [base['noun']] + post[:1]), ' '.join([base['noun']] + post[:1]), ' '.join(pre[:1] + [base['noun']]),
             base['noun']]
    short = next((w for w in words if len(w) <= NAME_MAX), words[-1])
    name = f"{base['cat']} — {short}"
    name = re.sub(r'\s+', ' ', name).strip()
    comment = (desc[0].rstrip('.') + '. ' + ', '.join(d for d in desc[1:] if d)).strip().rstrip(',') if len(desc) > 1 else desc[0]
    comment = comment[0].upper() + comment[1:]
    if not comment.endswith('.'):
        comment += '.'
    patch['Volume'] = fmt(float(levels.get(name, base.get('volume', -10))))
    return {'name': name, 'comment': comment, 'patch': patch, 'state': state, 'cat': base['cat'], 'duo': var.duo,
            'engines': [e for e in engines(patch) if e != 'Off'], 'fx': [fx['type'] for fx in var.fxs], 'base': base['key']}


def raw_values(patch):
    out = {}
    for k, v in patch.items():
        p = BY_NAME.get(k.lower())
        if p is None:
            raise SystemExit(f'no parameter "{k}"')
        try:
            out[p['index']] = genpresets.to_raw(p, v)
        except ValueError as e:
            raise SystemExit(f'{k} = {v}: {e}')
    return out


def distance(ra, rb, sa=None, sb=None):
    """The library test's measure: a choice (an enum, a switch or a small integer) counts 1 when it differs; anything else
    its difference over its range; the machine state counts 1 for each property that differs. Volume does not count."""
    d = 0.0
    for i, p in enumerate(PARAMS):
        if p['id'] == 'Volume':
            continue
        a = ra.get(i, p['def'])
        b = rb.get(i, p['def'])
        if a == b:
            continue
        span = p['max'] - p['min']
        d += 1.0 if (p['kind'] in ('enum', 'switch') or span <= 20) else abs(a - b) / span
    sa, sb = sa or {}, sb or {}
    for k in set(sa) | set(sb):
        if sa.get(k) != sb.get(k):
            d += 1.0
    return d


def existing_presets():
    """The hand-made presets above the marker: name -> (raw values, state)."""
    text = open(PRESETS, encoding='utf-8').read()
    head = text.split('\n# ---- Generated by')[0]
    out = {}
    cur = None
    for line in head.splitlines():
        s = line.strip()
        if s.startswith('preset '):
            name = s[len('preset '):].strip().strip('"')
            cur = out[name] = ({}, {})
        elif cur is not None and s.startswith('state ') and '=' in s:
            k, _, v = s[len('state '):].partition('=')
            cur[1][k.strip()] = v.strip()
        elif cur is not None and '=' in s and not s.startswith('#'):
            k, v = (x.strip() for x in s.split('=', 1))
            p = BY_NAME.get(k.lower())
            if p is not None:
                cur[0][p['index']] = genpresets.to_raw(p, v)
    return head, out


def variants(base):
    """Candidate variants of one base, best first: the plain one, then combinations of modifiers and effects chosen with the
    seeded generator; build() takes the first n that fit and are distinct."""
    rng = random.Random(stable(L.SEED, base['key']))
    yield Variant(base, [], [], False)
    allowed = (lambda m: m['key'] in base['only']) if base.get('only') else (lambda m: m['key'] not in base.get('no', ()))
    tone = [m for m in L.MODS if m['kind'] in ('tone', 'time') and allowed(m)]
    layer = [m for m in L.MODS if m['kind'] in ('layer', 'motion') and allowed(m)]
    pool = [L.FX[k] for k in base.get('fx', ())]
    for _ in range(120):
        mods = []
        if tone and rng.random() < 0.7:
            mods.append(rng.choice(tone))
        if layer and rng.random() < 0.55:
            mods.append(rng.choice(layer))
        fxs = []
        if pool and (rng.random() < 0.85 or not mods):
            fxs.append(rng.choice(pool))
            if rng.random() < 0.25:
                other = rng.choice(pool)
                if other['type'] != fxs[0]['type'] and (other['role'] != fxs[0]['role'] or other.get('bus') != fxs[0].get('bus')):
                    fxs.append(other)
        if not mods and not fxs:
            continue
        duo = rng.random() < base.get('duo', 0.35)
        yield Variant(base, mods, fxs, duo)


def build(levels):
    head, existing = existing_presets()
    made = []
    names = set(existing)
    raws = [(n, v[0], v[1]) for n, v in existing.items()]
    dropped = []
    for base in L.bases():
        got = 0
        for var in variants(base):
            if got >= base.get('n', 2):
                break
            r = realise(var, levels)
            if r is not None and (r['name'] in getattr(L, 'CURATED_OUT', ()) or any(w in r['name'] for w in getattr(L, 'CURATED_OUT_CONTAINS', ())) or r['name'].endswith(getattr(L, 'CURATED_OUT_SUFFIX', '\0'))):
                dropped.append((r['name'], 'curated out'))
                continue
            if r is None or r['name'] in names:
                dropped.append((base['key'], 'unfit' if r is None else 'name'))
                continue
            raw = raw_values(r['patch'])
            state = {k: v for k, v in r['state'].items()}
            near = None
            for (n2, ra, sa) in raws:
                if distance(raw, ra, state, sa) < MIN_DISTANCE:
                    near = n2
                    break
            if near:
                dropped.append((r['name'], 'near ' + near))
                continue
            r['raw'] = raw
            got += 1
            names.add(r['name'])
            raws.append((r['name'], raw, state))
            made.append(r)
    return head, made, dropped


def render(made):
    lines = []
    for r in made:
        lines.append(f'preset "{r["name"]}"')
        lines.append(f'comment "{r["comment"]}"')
        for k, v in r['patch'].items():
            lines.append(f'{k} = {v}')
        for k, v in r['state'].items():
            lines.append(f'state {k} = {v}')
        lines.append('')
    return '\n'.join(lines)


def report(made, dropped):
    from collections import Counter
    print(f'{len(made)} generated presets, {len(dropped)} dropped')
    cats = Counter(r['cat'] for r in made)
    print('categories:', dict(cats))
    eng = Counter(e for r in made for e in set(r['engines']))
    print('engines:', dict(eng))
    print('fx types:', dict(Counter(t for r in made for t in set(r['fx']))))
    print('layouts: Duo', sum(1 for r in made if r['duo']), 'Trio', sum(1 for r in made if not r['duo']))
    per = {}
    for r in made:
        per.setdefault(r['cat'], set()).update(r['engines'])
    print('engines per category:', {c: len(v) for c, v in per.items()})
    for n, why in dropped:
        print('  dropped', n, why)


def main(argv):
    levels = json.load(open(LEVELS)) if os.path.exists(LEVELS) else {}
    if '--apply-levels' in argv:
        table = argv[argv.index('--apply-levels') + 1]
        n = 0
        for line in open(table, encoding='utf-8'):
            parts = line.rstrip('\n').split('\t')
            if len(parts) < 3:
                continue
            name, level = parts[0], float(parts[1].replace('−', '-'))
            # The generated presets only (the table lists every Dye preset).
            if name not in GENERATED_NAMES():
                continue
            cur = float(levels.get(name, L.DEFAULT_VOLUME))
            levels[name] = round(max(-40.0, min(6.0, cur + (TARGET_DB - level))), 1)
            n += 1
        json.dump(dict(sorted(levels.items())), open(LEVELS, 'w', encoding='utf-8'), indent=0, ensure_ascii=False)
        open(LEVELS, 'a').write('\n')
        print(f'{n} levels updated')
        return
    head, made, dropped = build(levels)
    text = head.rstrip('\n') + '\n\n' + (MARKER % L.SEED) + '\n\n' + render(made)
    with open(PRESETS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    json.dump(dict(sorted(levels.items())), open(LEVELS, 'w', encoding='utf-8'), indent=0, ensure_ascii=False)
    open(LEVELS, 'a').write('\n')
    print(f'wrote {len(made)} generated presets to {PRESETS} ({len(dropped)} dropped)')
    if '--report' in argv:
        report(made, dropped)


_names = None


def GENERATED_NAMES():
    global _names
    if _names is None:
        text = open(PRESETS, encoding='utf-8').read()
        tail = text.split('\n# ---- Generated by', 1)[1] if '\n# ---- Generated by' in text else ''
        _names = set(re.findall(r'^preset "(.+)"$', tail, re.M))
    return _names


if __name__ == '__main__':
    main(sys.argv[1:])
