#!/usr/bin/env python3
"""Plug-in export generator (docs/specs/plugin-export.md §3): PluginExport/descriptors/*.json -> the C# and CMake files that turn
each Neo machine into a CLAP / VST3 / AU plug-in from its own engine and parameter table.

    python3 tools/gen-plugin-export.py            write the generated files
    python3 tools/gen-plugin-export.py --check    exit 1 when a generated file is out of date (CI)

A descriptor is a small JSON file (see PluginExport/descriptors/neo-filter.json):
  id, name, folder (under Machines/), namespace, engine (class of Engine/), machine + editor (classes of the machine's own
  files, for the editor library), kind effect|instrument, features (CLAP features after the kind's own), au (4-char AU
  subtype), description, process stereo|sidechain|synth, tempo (engine.Tempo), transport "ticks" (engine.Transport as
  FilterTransport), idle (engine.Idle), latency (false: the engine has none), tailSeconds, test {changes, settle} for ci/null-test.py.
Everything else (parameter ids, ranges, texts, units, groups, state, latency, ports) comes from the engine and its Params table at
run time; nothing is written per machine beyond the descriptor.
"""
import glob, json, os, sys

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
px = os.path.join(root, "PluginExport")
descs = [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(px, "descriptors", "*.json")))]
HEAD = "// <auto-generated> by tools/gen-plugin-export.py from PluginExport/descriptors/*.json. Do not edit; edit a descriptor and regenerate.\n"


def ident(d): return "A_" + d["engine"]


def adapter(d):
    ns, eng = d["namespace"], d["namespace"] + "." + d["engine"]
    inst = d["kind"] == "instrument"
    o = [f"    internal sealed class {ident(d)} : ExportEngine", "    {", f"        {eng} e;",
         f"        public override ParamDef[] Table => {ns}.Params.Table;",
         f"        public override int MaxBlock => {eng}.MaxBlock;",
         f"        public override void Create(ParamValues values) {{ e = new {eng}(values); }}",
         "        public override void SetSampleRate(float sr) => e.SetSampleRate(sr);",
         "        public override int Latency => e.Latency;" if not inst and d.get("latency", True) else "        public override int Latency => 0;"]
    o.append("        public override void Reset() => e.AllNotesOff(true);" if inst else "        public override void Reset() => e.Reset();")
    if d.get("idle"): o.append("        public override bool Idle => e.Idle;")
    tempo = "e.Tempo = tempo;" if d.get("tempo") else ""
    tr = ""
    if d.get("transport") == "ticks":
        tr = f"""
            var t = new {ns}.FilterTransport();
            if (playing && tempo > 0)
            {{
                const int tpb = 480;
                double ticks = beats * tpb, whole = Math.Floor(ticks);
                double spt = rate * 60.0 / (tempo * tpb);
                t.Playing = true; t.TicksPerBeat = tpb; t.Tick = (int)whole;
                t.SamplesPerTick = Math.Max(1, (int)Math.Round(spt)); t.PosInTick = (int)((ticks - whole) * t.SamplesPerTick);
            }}
            e.Transport = t;"""
    if tempo or tr:
        o.append(f"        public override void SetTransport(double tempo, bool playing, double beats, double rate)\n        {{\n            {tempo}{tr}\n        }}")
    p = d["process"]
    if p == "stereo": o.append("        public override bool Process(float[] l, float[] r, float[] kl, float[] kr, int n) { e.Process(l, r, n); return true; }")
    elif p == "sidechain": o.append("        public override bool Process(float[] l, float[] r, float[] kl, float[] kr, int n) { e.Process(l, r, kl, kr, n); return true; }")
    elif p == "synth": o.append("        public override bool Process(float[] l, float[] r, float[] kl, float[] kr, int n) => e.Process(l, r, n);")
    if inst:
        o += ["        public override void NoteOn(int key, int note, float velocity) => e.NoteOn(key, note, velocity);",
              "        public override void NoteOff(int key) => e.NoteOff(key);",
              "        public override void ModWheel(float v) => e.ModWheel(v);",
              "        public override void PitchBend(float v) => e.PitchBend(v);",
              "        public override void Sustain(bool down) => e.Sustain(down);",
              "        public override void Aftertouch(float v) => e.Aftertouch(v);",
              "        public override void AllNotesOff(bool hard) => e.AllNotesOff(hard);"]
    o.append("    }")
    return "\n".join(o)


def q(s): return json.dumps(s)


def registry():
    o = [HEAD + "using System;", "using NeoBuzz.Dsp;", "", "namespace NeoExport", "{"]
    o += [adapter(d) + "\n" for d in descs]
    o += ["    internal static partial class Registry", "    {", "        public static readonly PluginInfo[] All =", "        {"]
    for d in descs:
        feats = ", ".join(q(f) for f in (["instrument"] if d["kind"] == "instrument" else ["audio-effect"]) + d.get("features", []) + ["stereo"])
        o.append(f"            new PluginInfo({q(d['id'])}, {q(d['name'])}, {q(d['description'])}, new[] {{ {feats} }}, "
                 f"instrument: {str(d['kind'] == 'instrument').lower()}, sidechain: {str(d['process'] == 'sidechain').lower()}, gateIdle: {str(bool(d.get('idle'))).lower()}, tailSeconds: {d.get('tailSeconds', 0)}, make: () => new {ident(d)}()),")
    o += ["        };", "    }", "}", ""]
    return "\n".join(o)


def extras():
    seen = []
    for d in descs:
        for x in d.get("extra", []):
            if x not in seen: seen.append(x)
    return [f'    <Compile Include="..\\..\\Machines\\{x.replace("/", chr(92))}" Link="Machines\\Extra\\%(Filename)%(Extension)" />' for x in seen]


def dsp_props():
    o = ['<Project>', '  <!-- ' + HEAD.strip()[3:] + ' -->', '  <ItemGroup>']
    for d in descs:
        o.append(f'    <Compile Include="..\\..\\Machines\\{d["folder"]}\\Engine\\**\\*.cs" Link="Machines\\{d["folder"]}\\%(RecursiveDir)%(Filename)%(Extension)" />')
    o += extras()
    o += ['  </ItemGroup>', '</Project>', '']
    return "\n".join(o)


def editor_props():
    o = ['<Project>', '  <!-- ' + HEAD.strip()[3:] + ' -->', '  <ItemGroup>']
    for d in descs:
        f = d["folder"]
        o.append(f'    <Compile Include="..\\..\\Machines\\{f}\\**\\*.cs" Exclude="..\\..\\Machines\\{f}\\obj\\**;..\\..\\Machines\\{f}\\bin\\**" Link="Machines\\{f}\\%(RecursiveDir)%(Filename)%(Extension)" />')
    o += extras()
    o += ['  </ItemGroup>', '</Project>', '']
    return "\n".join(o)


def editors():
    o = [HEAD + "using System;", "using NeoBuzz.Editor;", "", "namespace NeoExport", "{", "    internal static partial class EditorRegistry", "    {",
         "        /// <summary>A plug-in's Neo editor and the machine class the editor reads (null host: no engine thread, only its own Values).</summary>",
         "        public static bool TryMake(string pluginId, out NeoEditor editor, out object machine)", "        {", "            switch (pluginId)", "            {"]
    for d in descs:
        ns = d["namespace"]
        o.append(f"                case {q(d['id'])}:")
        o.append(f"                    {{ var m = new {ns}.{d['machine']}(null); machine = m; editor = new {ns}.{d['editor']}(); return true; }}")
    o += ["                default: editor = null; machine = null; return false;", "            }", "        }", "    }", "}", ""]
    return "\n".join(o)


def cmake():
    o = ["# <auto-generated> by tools/gen-plugin-export.py from PluginExport/descriptors/*.json. Do not edit.",
         "# name|AU subtype|AU type|CLAP id", "set(NEO_PLUGINS"]
    for d in descs:
        o.append(f'  "{d["name"]}|{d["au"]}|{"aumu" if d["kind"] == "instrument" else "aufx"}|{d["id"]}"')
    o += [")", ""]
    return "\n".join(o)


def table(d):
    """Params.def of the machine: id -> (display name, min, max, default)."""
    import re
    out = {}
    for line in open(os.path.join(root, "Machines", d["folder"], "Params.def"), encoding="utf-8"):
        m = re.match(r'^(\w+)\s+"([^"]*)"\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)', line)
        if m: out[m.group(1)] = (m.group(2), int(m.group(3)), int(m.group(4)), int(m.group(5)))
    return out


def manifest():
    res = []
    for d in descs:
        t, tab = dict(d.get("test", {})), table(d)
        ch = []
        for pid, raw in t.get("changes", []):
            name, lo, hi, _ = tab[pid]
            r = int(str(raw).split(":")[1])
            ch.append({"param": name, "native": f"raw:{r}", "slot": f"raw:{round(65534 * (r - lo) / (hi - lo))}"})
        t["changes"] = ch
        res.append({"id": d["id"], "name": d["name"], "kind": d["kind"], "au": d["au"], "sidechain": d["process"] == "sidechain", "test": t,
                    "paramCount": len(tab), "latencyDependsOnParams": d["name"] == "Neo EQ"})
    return json.dumps(res, indent=1) + "\n"


outputs = {
    os.path.join(px, "dsp", "Generated", "Registry.g.cs"): registry(),
    os.path.join(px, "dsp", "Generated", "Sources.g.props"): dsp_props(),
    os.path.join(px, "editor", "Generated", "EditorRegistry.g.cs"): editors(),
    os.path.join(px, "editor", "Generated", "Sources.g.props"): editor_props(),
    os.path.join(px, "cmake", "plugins.cmake"): cmake(),
    os.path.join(px, "plugins.json"): manifest(),
}
check = "--check" in sys.argv
bad = 0
for path, text in outputs.items():
    old = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
    if old == text: continue
    if check:
        print("out of date:", os.path.relpath(path, root)); bad += 1
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8", newline="").write(text)
        print("wrote", os.path.relpath(path, root))
sys.exit(1 if bad else 0)
