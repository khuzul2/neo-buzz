// Fork (docs/specs/mcp-server.md §12.2, U1): profiled draft manifests as the server reads them
// (status, note input and pitch offset, health, track parameters, table mappings with infinities)
// and notes for machines that take them in their tracks (voices, Note events, read back).
using System.IO;
using System.Linq;
using System.Text.Json.Nodes;
using ReBuzz.Agent.Mcp;
using ReBuzz.Agent.Model;
using V = ReBuzz.Agent.Model.ValueResolver;

namespace ReBuzz.AgentTests
{
    [TestFixture]
    public class DraftManifestTests
    {
        const string Draft = """
        {
          "format": "rebuzz-machine-manifest/1",
          "gear": "Test Synth",
          "kind": "generator",
          "status": "draft",
          "source": "profiled by tools/machine-profiler.py on linux, 2026-11-03; not curated",
          "type": "monosynth",
          "summary": "Monosynth (profiled draft).",
          "tracks": 4,
          "notes": { "input": "tracks", "pitch_offset": -12, "pitched": true, "polyphony": 4 },
          "health": { "status": "unhealthy", "problems": ["NaN or runaway output on noise"] },
          "parameters": [
            { "index": 0, "name": "Env A", "min": 0, "max": 127, "default": 5, "kind": "time", "a": 1, "b": 4000, "unit": "ms",
              "description": "Attack time (1 ms – 4 s exponential)", "confidence": "description" },
            { "index": 1, "name": "Volume", "min": 0, "max": 4, "default": 4, "kind": "table", "unit": "dB",
              "points": [[0, "-inf"], [1, -24.0], [2, -12.0], [3, -6.0], [4, 0.0]], "confidence": "values" },
            { "index": 2, "name": "Cutoff", "min": 0, "max": 127, "default": 64, "kind": "freq", "a": 20, "b": 20000, "unit": "Hz", "confidence": "values" }
          ],
          "track_parameters": [
            { "index": 1, "name": "Level", "min": 0, "max": 100, "default": 100, "kind": "linear", "a": 0, "b": 100, "unit": "%" }
          ]
        }
        """;

        static ParamInfo Info(ManifestParameter p, System.Func<int, string> describe = null, bool textsFirst = true) => new()
        {
            Name = p.Name, Min = p.Min, Max = p.Max, Default = p.Default, Mapping = p.Mapping, TextsFirst = textsFirst,
            Describe = describe ?? (raw => raw.ToString()),
        };

        [Test]
        public void DraftsSayWhatTheyAreAndHowTheyTakeNotes()
        {
            var m = MachineManifest.Parse(Draft);
            Assert.That(m.IsDraft, Is.True);
            Assert.That(m.Quality, Is.EqualTo("draft"));
            Assert.That(m.Type, Is.EqualTo("monosynth"));
            Assert.That(m.Notes.Input, Is.EqualTo("tracks"));
            Assert.That(m.Notes.PitchOffset, Is.EqualTo(-12));
            Assert.That(m.Notes.Polyphony, Is.EqualTo(4));
            Assert.That(m.Health.Unhealthy, Is.True);
            Assert.That(m.Health.Problems, Has.Count.EqualTo(1));
            Assert.That(m.FindTrack("level")!.Mapping.Unit, Is.EqualTo("%"));
            Assert.That(m.Find("Env A")!.Approximate, Is.True, "read from its description");
            Assert.That(m.Find("Cutoff")!.Approximate, Is.False, "fitted to its value texts");
        }

        [Test]
        public void GeneratedManifestsStayExactWithNoNotesOrHealth()
        {
            var m = MachineManifest.Parse("""{"format": "rebuzz-machine-manifest/1", "gear": "Neo X", "source": "generated by tools/gen-machine-params.py", "track_parameters": ["Note", "Velocity"], "parameters": []}""");
            Assert.That(m.IsDraft, Is.False);
            Assert.That(m.Quality, Is.EqualTo("generated"));
            Assert.That(m.Notes, Is.Null);
            Assert.That(m.Health, Is.Null);
            Assert.That(m.TrackParameters, Is.Empty, "names alone describe nothing");
        }

        [Test]
        public void UnitsThroughADraftsMappings()
        {
            var m = MachineManifest.Parse(Draft);
            var env = Info(m.Find("Env A")!);
            int raw = V.Resolve(env, JsonValue.Create("250 ms"), env.Default);
            Assert.That(env.Mapping.Value(raw, 0, 127), Is.EqualTo(0.25).Within(0.02), "milliseconds in the manifest are seconds inside");
            var cutoff = Info(m.Find("Cutoff")!);
            Assert.That(cutoff.Mapping.Value(V.Resolve(cutoff, JsonValue.Create("1 kHz"), 64), 0, 127), Is.EqualTo(1000).Within(60));
        }

        [Test]
        public void TableMappingsInterpolateAndKeepMinusInfinity()
        {
            var vol = Info(MachineManifest.Parse(Draft).Find("Volume")!);
            Assert.That(vol.Mapping.Value(0, 0, 4), Is.EqualTo(double.NegativeInfinity));
            Assert.That(vol.Mapping.Value(3, 0, 4), Is.EqualTo(-6.0));
            Assert.That(V.Resolve(vol, JsonValue.Create("-7 dB"), 4), Is.EqualTo(3), "nearest point");
            Assert.That(V.Resolve(vol, JsonValue.Create("-inf dB"), 4), Is.EqualTo(0));
            Assert.That(V.Resolve(vol, JsonValue.Create("+6 dB"), 4, V.Mode.By), Is.EqualTo(4), "clamped to the top: -6 + 6 = 0 dB");
        }

        [Test]
        public void ADraftTakesTheMachinesOwnTextsFirst()
        {
            // A draft fitted a line through 1..127, but raw 0 reads "Off".
            var p = new ParamInfo
            {
                Name = "Delay", Min = 0, Max = 127, Default = 0, TextsFirst = true,
                Mapping = new ParamMapping { Kind = MappingKind.Linear, A = 0, B = 127, Unit = "" },
                Describe = raw => raw == 0 ? "Off" : raw.ToString(),
            };
            Assert.That(V.Resolve(p, JsonValue.Create("Off"), 64), Is.EqualTo(0));
            Assert.That(V.Resolve(p, JsonValue.Create("64"), 0), Is.EqualTo(64));
        }

        [Test]
        public void EveryCommittedDraftParses()
        {
            string root = TestContext.CurrentContext.TestDirectory;
            while (root != null && !Directory.Exists(Path.Combine(root, "Machines", "Manifests"))) root = Path.GetDirectoryName(root)!;
            Assert.That(root, Is.Not.Null, "Machines/Manifests in the repository");
            var files = Directory.GetFiles(Path.Combine(root!, "Machines", "Manifests"), "*" + MachineManifest.Suffix, SearchOption.AllDirectories);
            Assert.That(files, Is.Not.Empty);
            foreach (var file in files)
            {
                var m = MachineManifest.Load(file)!;
                string sub = Path.GetFileName(Path.GetDirectoryName(file))!;
                Assert.That(Path.GetFileName(file), Is.EqualTo(m.Gear + MachineManifest.Suffix));
                Assert.That(sub, Is.AnyOf("Generators", "Effects"), file);
                Assert.That(m.IsDraft, Is.True, m.Gear + ": drafts only here; generated manifests live with their machines");
                Assert.That(m.Kind, Is.AnyOf("generator", "effect"));
                Assert.That(m.Summary, Does.Contain("profiled draft"), m.Gear);
                Assert.That(m.Health, Is.Not.Null, m.Gear);
                foreach (var p in m.Parameters.Concat(m.TrackParameters))
                {
                    Assert.That(p.Default, Is.InRange(p.Min, p.Max), $"{m.Gear} {p.Name}");
                    Assert.That(p.Confidence, Is.AnyOf("values", "description"), $"{m.Gear} {p.Name}");
                    double v = p.Mapping.Value(p.Default, p.Min, p.Max);
                    Assert.That(double.IsNaN(v), Is.False, $"{m.Gear} {p.Name}: its default maps to a value");
                }
            }
        }

        [Test]
        public void ChordsGetAVoiceEach()
        {
            var notes = new[]
            {
                new NoteEvent(0, 960, 60, 100), new NoteEvent(0, 960, 64, 100), new NoteEvent(0, 960, 67, 100),
                new NoteEvent(960, 960, 72, 100),   // after the chord: the first free track again
            };
            var (tracks, needed) = TrackNotes.Allocate(notes);
            Assert.That(needed, Is.EqualTo(3));
            Assert.That(tracks, Is.EqualTo(new[] { 0, 1, 2, 0 }));
        }

        [Test]
        public void TrackNotesRoundTrip()
        {
            const int tick = 240, pattern = 16 * tick;   // a 16-tick pattern
            var notes = new[]
            {
                new NoteEvent(0, 4 * tick, 69, 100),
                new NoteEvent(0, 2 * tick, 72, 64),
                new NoteEvent(4 * tick, 4 * tick, 71, 127),            // straight after the first: no note-off between
                new NoteEvent(12 * tick, 4 * tick, 60, 100),           // to the pattern's end: let go on its last tick
            };
            var (tracks, needed) = TrackNotes.Allocate(notes);
            var events = TrackNotes.Events(notes, tracks, pattern, tick, (0, 127));
            Assert.That(events.Where(e => e.Note == TrackNotes.Off).Select(e => e.Time), Is.EquivalentTo(new[] { 2 * tick, 8 * tick, 15 * tick }));
            Assert.That(events.First(e => e.Time == 0 && e.Note == Pitch.ToBuzz(69)).Velocity, Is.EqualTo(100));
            var back = TrackNotes.Read(events.Select(e => (e.Track, e.Time, e.Note)), pattern, tick,
                events.Where(e => e.Velocity.HasValue).ToDictionary(e => (e.Track, e.Time), e => e.Velocity!.Value), (0, 127));
            Assert.That(back, Is.EqualTo(notes.OrderBy(n => n.Time).ThenBy(n => n.Pitch).ToList()));
            Assert.That(needed, Is.EqualTo(2));
        }

        [Test]
        public void PitchOffsetsAndTheirLimits()
        {
            Assert.That(TrackNotes.Sent(69, -12, 127, "X"), Is.EqualTo(57));
            var e = Assert.Throws<ToolError>(() => TrackNotes.Sent(8, -12, 127, "Old Synth"));
            Assert.That(e!.Message, Does.Contain("pitch offset (-12 semitones").And.Contain("C0"));
            Assert.Throws<ToolError>(() => TrackNotes.Sent(125, 0, 119, "Tracker"));
            Assert.That(TrackNotes.ToBuzz(120), Is.EqualTo(-1));
            Assert.That(TrackNotes.FromBuzz(TrackNotes.Off), Is.EqualTo(-1));
        }
    }
