        [Test]
        public void TableMappingsInterpolateAndKeepMinusInfinity()
        {
            var vol = Info(MachineManifest.Parse(Draft).Find("Volume")!);
            Assert.That(vol.Mapping.Value(0, 0, 4), Is.EqualTo(double.NegativeInfinity));
            Assert.That(vol.Mapping.Value(3, 0, 4), Is.EqualTo(-6.0));
