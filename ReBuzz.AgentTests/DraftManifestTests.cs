        }

        [Test]
        public void ADraftTakesTheMachinesOwnTextsFirst()
        {
            // A draft fitted a line through 1..127, but raw 0 reads "Off".
            var p = new ParamInfo
            {
                Name = "Delay", Min = 0, Max = 127, Default = 0, TextsFirst = true,
                Mapping = new ParamMapping { Kind = MappingKind.Linear, A = 0, B = 127, Unit = "" },
