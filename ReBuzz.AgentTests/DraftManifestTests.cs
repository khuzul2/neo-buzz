        static ParamInfo Info(ManifestParameter p, System.Func<int, string> describe = null, bool textsFirst = true) => new()
        {
            Name = p.Name, Min = p.Min, Max = p.Max, Default = p.Default, Mapping = p.Mapping, TextsFirst = textsFirst,
            Describe = describe ?? (raw => raw.ToString()),
        };

